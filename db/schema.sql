CREATE TABLE communications (
    id            NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    published_on  DATE           NOT NULL,
    department    VARCHAR2(100)  NOT NULL,
    title         VARCHAR2(300)  NOT NULL,
    url           VARCHAR2(500),
    highlighted   NUMBER(1)      DEFAULT 0 NOT NULL,
    created_at    TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT communications_highlighted_ck CHECK (highlighted IN (0, 1))
);

CREATE INDEX communications_published_ix ON communications (published_on DESC);

CREATE TABLE facts (
    id          NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    title       VARCHAR2(300) NOT NULL,
    url         VARCHAR2(500),
    active      NUMBER(1)     DEFAULT 1 NOT NULL,
    sort_order  NUMBER(5)     DEFAULT 0 NOT NULL,
    created_at  TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT facts_active_ck CHECK (active IN (0, 1))
);

